ok=0; skip=0; fail=0; failed=()

get() {  # get <filename> <url>
  local fn="$1" url="$2" path="$DEST/$1"
  if [ -s "$path" ] && [ "$(head -c 5 "$path" 2>/dev/null)" = "%PDF-" ]; then
    skip=$((skip+1)); return
  fi
  curl -sL -A "$UA" --max-time 90 -o "$path.part" "$url" 2>/dev/null
  if [ -s "$path.part" ] && [ "$(head -c 5 "$path.part")" = "%PDF-" ]; then
    mv "$path.part" "$path"; ok=$((ok+1)); printf "  ok    %s\n" "$fn"
  else
    rm -f "$path.part"; fail=$((fail+1)); failed+=("$fn"); printf "  FAIL  %s\n" "$fn"
  fi
  sleep 1
}

